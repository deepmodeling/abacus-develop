    /**
     * @brief Get the dftd3 params object. 
     * dftd3 method fall back: bjm -> bj -> zero
     *                         zerom -> zero
     * 
     * @param xc the functional name
     * @param d3method the d3 method, can be "bj", "zero-damping", "bj-modified", "zero-damping-modified", "op"
     * @param param the dftd3 parameters, ALL_KEYS = {'s6', 'rs6', 'a1', 's8', 'rs8', 'a2', 's9', 'alp', 'bet'}
     */
    void search(const std::string& xc, 
                const std::string& method, 
                std::vector<double>& param)
    {
        const std::string xc_lowercase = lowercase(xc);
        const std::vector<std::string> allowed_ = { "bj", "zero", "bjm", "zerom", "op" };
        assert(std::find(allowed_.begin(), allowed_.end(), method) != allowed_.end());
        if (method == "op")
        {
            if (op.find(xc_lowercase) != op.end())
            {
                param = op[xc_lowercase];
            }
            else
            {
                std::cout << " WARNING: DFT-D3 (Optimized-Power) parameter for XC " << xc << " not found, fall back to DFT-D3 PBE" << std::endl;
                search("PBE", "zero", param);
            }
        }
        else if (method == "bjm")
        {
            if (bjm.find(xc_lowercase) != bjm.end())
            {
                param = bjm[xc_lowercase];
            }
            else
            {
                std::cout << " WARNING: DFT-D3 (modified BJ-damping) parameter for XC " << xc << " not found, fall back to DFT-D3 (BJ-damping)" << std::endl;
                search(xc, "bj", param);
            }
        }
        else if (method == "bj")
        {
            if (bj.find(xc_lowercase) != bj.end())
            {
                param = bj[xc_lowercase];
            }
            else
            {
                std::cout << " WARNING: DFT-D3 (BJ-damping) parameter for XC " << xc << " not found, fall back to DFT-D3" << std::endl;
                search(xc, "zero", param);
            }
        }
        else if (method == "zerom")
        {
            if (zerom.find(xc_lowercase) != zerom.end())
            {
                param = zerom[xc_lowercase];
            }
            else
            {
                std::cout << " WARNING: DFT-D3 (modified) parameter for XC " << xc << " not found, fall back to DFT-D3" << std::endl;
                search(xc, "zero", param);
            }
        }
        else
        {
            if (zero.find(xc_lowercase) != zero.end())
            {
                param = zero[xc_lowercase];
            }
            else
            {
                std::cout << " WARNING: DFT-D3 parameter for XC " << xc << " not found, fall back to DFT-D3 PBE" << std::endl;
                search("PBE", "zero", param);
            }
        }
    }

    std::string lowercase(const std::string& s)
    {
        std::string result = s;
        std::transform(s.begin(), s.end(), result.begin(), ::tolower);
        return result;
    }
