FsshDriver::FsshDriver() : nstates_(0), nbasis_(0), dt_(0.0), current_state_(0),
                           nocc_(0), nks_total_(0) {
    std::random_device rd;
    gen_.seed(rd());
    rand_dist_ = std::uniform_real_distribution<double>(0.0, 1.0);
}

