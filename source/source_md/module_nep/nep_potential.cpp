/**
 * @file nep_potential.cpp
 * @brief Implementation of the NEP potential for molecular dynamics.
 *
 * This file contains the implementation of the NEP potential, which is used for solving the energy and forces in a
 * NEP simulation.
 * NEP is a method for training deep neural networks to accurately predict the potential energy surface of a
 * molecular system.
 *
 * For more information about NEP, see the following reference:
 * 1. https://gpumd.org/potentials/nep.html
 * 2. https://doi.org/10.1002/mgea.70028
 *
 * @author MoseyQAQ
 * @date 2025-10-10
 */
